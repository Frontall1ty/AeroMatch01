// Renders the load view's vehicle pictures from the 3D models (src/three) and writes them to public/vehicles/,
// with the cargo space of each picture in src/lib/loadStills.ts. Run after changing a model:
//   node scripts/render-stills.mjs
import { createRequire } from "node:module";
import { mkdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
const require = createRequire(import.meta.url);
const esbuild = require("esbuild");
const sharp = require("sharp");
const { chromium } = require("playwright");

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const bundle = await esbuild.build({
  stdin: { contents: 'import { renderStill } from "@/three/stills"; window.renderStill = renderStill;', resolveDir: root, loader: "ts" },
  bundle: true,
  format: "iife",
  write: false,
  alias: { "@": path.join(root, "src") },
  logLevel: "error",
});
const browser = await chromium.launch({ args: ["--use-angle=swiftshader", "--enable-unsafe-swiftshader"] });
const page = await browser.newPage();
await page.setContent("<!doctype html><html><body></body></html>");
await page.addScriptTag({ content: bundle.outputFiles[0].text });
const out = path.join(root, "public/vehicles");
mkdirSync(out, { recursive: true });
const WIDTH = 1600;
const stills = {};
for (const kind of ["truck", "plane", "wagon", "container", "ship"]) {
  const r = await page.evaluate(([k, w]) => window.renderStill(k, w), [kind, WIDTH]);
  const png = Buffer.from(r.url.split(",")[1], "base64");
  await sharp(png).webp({ quality: 84, alphaQuality: 90, effort: 6 }).toFile(path.join(out, `${kind}.webp`));
  stills[kind] = { src: `/vehicles/${kind}.webp`, w: r.w, h: r.h, area: r.area };
  console.log(kind, r.w, "x", r.h, JSON.stringify(r.area));
}
await browser.close();
writeFileSync(
  path.join(root, "src/lib/loadStills.ts"),
  `// Generated by scripts/render-stills.mjs from the 3D models in src/three. Do not edit by hand.\n` +
    `import type { LoadKind } from "./load";\n\n` +
    `/** A rendered side view of each vehicle, and where its cargo space is, in pixels of the picture. */\n` +
    `export const LOAD_STILLS: Record<LoadKind, { src: string; w: number; h: number; area: { x: number; y: number; w: number; h: number } }> = ${JSON.stringify(stills, null, 2)};\n`,
);
